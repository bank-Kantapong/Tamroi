export function localizeProvinceName(province: string, locale: Locale): string {
  if (locale === "th" && THAI_PROVINCE_LABELS[province]) {
    return THAI_PROVINCE_LABELS[province];
  }
  return province;
}

export function localizeCategoryName(category: string, locale: Locale): string {
  if (locale === "th" && THAI_CATEGORY_LABELS[category]) {
    return THAI_CATEGORY_LABELS[category];
  }
  return category;
}

export function localizeTrip<T extends Trip | TripListItem>(
  trip: T,
  locale: Locale
): T {
  if (locale !== "th") return trip;
  const override = SAMPLE_TRIP_TH[trip.slug];
  if (!override) return trip;
  return {
    ...trip,
    ...override,
  };
}

export function localizeStop(stop: TripStop, locale: Locale): TripStop {
  if (locale !== "th") return stop;
  const override = SAMPLE_STOP_TH[stop.id];
  if (!override) return stop;
  return {
    ...stop,
    ...override,
  };
}

export function localizeTripWithStops(
  trip: TripWithStops,
  locale: Locale
): TripWithStops {
  if (locale !== "th") return trip;
  const localizedTrip = localizeTrip(trip, locale);
  return {
    ...localizedTrip,
    stops: trip.stops.map((s) => localizeStop(s, locale)),
  };
}

